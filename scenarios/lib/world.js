// document factories: same shapes world-app commits (see worldlib / web/src/components/Composer.tsx)
export const docs = {
    entity: (ccid, domain) => ({
        kind: 'entity',
        author: ccid,
        schema: SCHEMA.entity,
        value: { domain },
        createdAt: new Date(),
    }),
    enact: (ccid, ckid) => ({
        kind: 'record',
        key: uri.keys(ccid, ckid),
        author: ccid,
        schema: SCHEMA.subkey,
        value: { ckid },
        onUpdate: 'retain',
        createdAt: new Date(),
    }),
    timeline: (ccid, kind) => {
        const doc = {
            kind: 'record',
            key: uri.timeline(ccid, kind),
            author: ccid,
            schema: SCHEMA.userTimeline,
            value: {},
            createdAt: new Date(),
        };
        if (kind === 'notify') {
            doc.policy = {
                entries: [
                    { url: POLICY.restrictReaders, params: { entities: [ccid] } },
                    { url: POLICY.writePublic },
                ],
            };
        }
        return doc;
    },
    profile: (ccid, username) => ({
        kind: 'record',
        key: uri.profile(ccid),
        author: ccid,
        schema: SCHEMA.profile,
        value: { username, description: 'generated by xk6-concrnt', avatar: '', banner: '' },
        createdAt: new Date(),
    }),
    list: (ccid, id, name) => ({
        kind: 'record',
        key: uri.list(ccid, id),
        author: ccid,
        schema: SCHEMA.list,
        value: { name },
        createdAt: new Date(),
    }),
    pinnedLists: (ccid, listURI) => ({
        kind: 'record',
        key: uri.lists(ccid),
        author: ccid,
        schema: SCHEMA.pinnedLists,
        value: [{ uri: listURI, defaultPostHome: true, defaultPostTimelines: [] }],
        createdAt: new Date(),
    }),
    listItem: (ccid, listURI, itemKey, href, schema) => ({
        kind: 'record',
        key: `${listURI}/${itemKey}`,
        author: ccid,
        schema: SCHEMA.reference,
        value: { href, schema },
        createdAt: new Date(),
    }),
    markdown: (ccid, postKey, body, distributes) => ({
        kind: 'record',
        key: postKey,
        author: ccid,
        schema: SCHEMA.markdown,
        value: { body, emojis: {} },
        distributes,
        createdAt: new Date(),
    }),
    reply: (ccid, postKey, body, targetURI, targetAuthor, distributes) => ({
        kind: 'record',
        key: postKey,
        author: ccid,
        schema: SCHEMA.reply,
        value: { body, targetURI, replyToMessageAuthor: targetAuthor, emojis: {} },
        distributes,
        createdAt: new Date(),
    }),
    reroute: (ccid, postKey, targetURI, targetAuthor, distributes) => ({
        kind: 'record',
        key: postKey,
        author: ccid,
        schema: SCHEMA.reroute,
        value: { targetURI, rerouteMessageAuthor: targetAuthor },
        distributes,
        createdAt: new Date(),
    }),
    like: (ccid, targetURI, targetAuthor) => ({
        kind: 'association',
        author: ccid,
        schema: SCHEMA.like,
        associate: targetURI,
        value: { profileURI: uri.profile(ccid) },
        distributes: [uri.timeline(ccid, 'activity'), uri.timeline(targetAuthor, 'notify')],
        createdAt: new Date(),
    }),
    reaction: (ccid, targetURI, targetAuthor, shortcode, imageUrl) => ({
        kind: 'association',
        author: ccid,
        schema: SCHEMA.reaction,
        associate: targetURI,
        associationVariant: imageUrl,
        value: { shortcode, imageUrl, profileURI: uri.profile(ccid) },
        distributes: [uri.timeline(ccid, 'activity'), uri.timeline(targetAuthor, 'notify')],
        createdAt: new Date(),
    }),
    replyAssoc: (ccid, targetURI, targetAuthor, newPostURI) => ({
        kind: 'association',
        author: ccid,
        schema: SCHEMA.replyAssoc,
        associate: targetURI,
        value: { targetURI: newPostURI, profileURI: uri.profile(ccid) },
        distributes: [uri.timeline(ccid, 'activity'), uri.timeline(targetAuthor, 'notify')],
        createdAt: new Date(),
    }),
    rerouteAssoc: (ccid, targetURI, targetAuthor, newPostURI) => ({
        kind: 'association',
        author: ccid,
        schema: SCHEMA.rerouteAssoc,
        associate: targetURI,
        value: { targetURI: newPostURI, profileURI: uri.profile(ccid) },
        distributes: [uri.timeline(ccid, 'activity'), uri.timeline(targetAuthor, 'notify')],
        createdAt: new Date(),
    }),
    followAck: (ccid, target) => ({
        kind: 'ack',
        author: ccid,
        schema: SCHEMA.followAck,
        value: {},
        associate: uri.entity(target),
        distributes: [uri.timeline(ccid, 'activity'), uri.timeline(target, 'notify')],
        createdAt: new Date(),
    }),
};
